function j(...chunks: (string | string[])[]): string {
  const flat: string[] = [];
  for (const c of chunks) {
    if (Array.isArray(c)) flat.push(...c);
    else flat.push(c);
  }
  return flat.join(' ');
}

/** מילות מפתח המופקות ממזהה העוגן (חיפוש חופשי לפי מבנה המזהה). */
export function anchorSlugTerms(anchorId: string): string {
  const tail = anchorId.replace(/^settings-anchor-/, '');
  return tail.replace(/-/g, ' ');
}

/** נרמול לאחידות חיפוש: אותיות קטנות + אותיות סופיות בעברית למפתח רגיל. */
export function normalizeForSearch(s: string): string {
  let t = s.toLowerCase();
  t = t.replace(/ך/g, 'כ').replace(/ם/g, 'מ').replace(/ן/g, 'נ').replace(/ף/g, 'פ').replace(/ץ/g, 'צ');
  return t;
}

